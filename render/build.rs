//! Translates the WGSL shaders (../shaders/) to GLSL ES 3.00 for WebGL2 with naga, as wgpu does for WebGL. Each
//! program gets its vertex and fragment GLSL, and what the GL side needs to feed it: its uniforms' offsets in
//! their uniform block, the blocks' names in each stage, and its textures' GLSL names. Written to
//! $OUT_DIR/shaders.rs, which src/shaders.rs includes.

use std::fmt::Write;
use std::path::Path;

use naga::back::glsl;
use naga::valid::{Capabilities, ValidationFlags, Validator};

/// Each program: its name, its shader file, and its vertex and fragment entry points.
const PROGRAMS: &[(&str, &str, &str, &str)] = &[
    ("MESH", "mesh", "vs", "fs"),
    ("MESH_IDS", "mesh", "vs", "fs_ids"),
    ("EDGES", "mesh", "vs", "fs_edges"),
    ("POINTS", "points", "vs", "fs"),
    ("POINTS_IDS", "points", "vs", "fs_ids"),
    ("LINES", "lines", "vs", "fs"),
    ("LINES_IDS", "lines", "vs", "fs_ids"),
    ("VECTORS", "vectors", "vs", "fs"),
    ("VECTORS_IDS", "vectors", "vs", "fs_ids"),
];

fn main() {
    println!("cargo:rerun-if-changed=../shaders");
    let common = std::fs::read_to_string("../shaders/common.wgsl").unwrap();
    let mut out = String::from("// Generated by build.rs from shaders/*.wgsl: don't edit.\n\n");

    for &(name, file, vs, fs) in PROGRAMS {
        let source = format!("{common}\n{}", std::fs::read_to_string(format!("../shaders/{file}.wgsl")).unwrap());
        let module = naga::front::wgsl::parse_str(&source).unwrap_or_else(|e| panic!("{}", e.emit_to_string(&source)));
        let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
            .validate(&module)
            .unwrap_or_else(|e| panic!("shaders/{file}.wgsl: {}", e.emit_to_string(&source)));

        let mut blocks = Vec::new();
        let mut textures = Vec::new();
        let mut glsl = |stage, entry: &str| -> String {
            let options = glsl::Options {
                version: glsl::Version::Embedded { version: 300, is_webgl: true },
                writer_flags: glsl::WriterFlags::empty(),
                ..Default::default()
            };
            let pipeline = glsl::PipelineOptions { shader_stage: stage, entry_point: entry.into(), multiview: None };
            let mut code = String::new();
            let mut writer = glsl::Writer::new(&mut code, &module, &info, &options, &pipeline, Default::default())
                .unwrap_or_else(|e| panic!("{file}.wgsl, {entry}: {e}"));
            let reflection = writer.write().unwrap_or_else(|e| panic!("{file}.wgsl, {entry}: {e}"));
            blocks.extend(reflection.uniforms.into_values());
            for (glsl_name, mapping) in reflection.texture_mapping {
                let alias = module.global_variables[mapping.texture].name.clone().unwrap_or_default();
                textures.push((alias, glsl_name));
            }
            code
        };
        let vertex = glsl(naga::ShaderStage::Vertex, vs);
        let fragment = glsl(naga::ShaderStage::Fragment, fs);

        // The uniforms: the members of the `u` struct, with their offsets and sizes in its block.
        let mut uniforms = Vec::new();
        let mut size = 0;
        for (_, var) in module.global_variables.iter() {
            if var.space != naga::AddressSpace::Uniform {
                continue;
            }
            let ty = &module.types[var.ty];
            size = ty.inner.size(module.to_ctx());
            if let naga::TypeInner::Struct { members, .. } = &ty.inner {
                for m in members {
                    uniforms.push((m.name.clone().unwrap(), m.offset, module.types[m.ty].inner.size(module.to_ctx())));
                }
            }
        }

        writeln!(out, "pub const {name}: ShaderDef = ShaderDef {{").unwrap();
        writeln!(out, "    module: {file:?},").unwrap();
        writeln!(out, "    entry_points: ({vs:?}, {fs:?}),").unwrap();
        writeln!(out, "    vertex: {vertex:?},").unwrap();
        writeln!(out, "    fragment: {fragment:?},").unwrap();
        writeln!(out, "    blocks: &{blocks:?},").unwrap();
        writeln!(out, "    uniforms: &{uniforms:?},").unwrap();
        writeln!(out, "    textures: &{textures:?},").unwrap();
        writeln!(out, "    size: {size},").unwrap();
        writeln!(out, "}};\n").unwrap();
    }
    // Every program, and each shader file's WGSL (with common.wgsl), for running them outside WebGL.
    let names: Vec<String> = PROGRAMS.iter().map(|p| format!("&{}", p.0)).collect();
    writeln!(out, "pub const ALL: &[&ShaderDef] = &[{}];\n", names.join(", ")).unwrap();
    let mut files: Vec<&str> = PROGRAMS.iter().map(|p| p.1).collect();
    files.dedup();
    writeln!(out, "pub const WGSL: &[(&str, &str)] = &[").unwrap();
    for file in files {
        let source = format!("{common}\n{}", std::fs::read_to_string(format!("../shaders/{file}.wgsl")).unwrap());
        writeln!(out, "    ({file:?}, {source:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    let path = Path::new(&std::env::var("OUT_DIR").unwrap()).join("shaders.rs");
    std::fs::write(path, out).unwrap();
}
